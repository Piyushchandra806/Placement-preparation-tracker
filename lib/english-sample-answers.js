/**
 * Normalizes prompt text for fuzzy / exact matching
 */
function normalizeKey(str) {
  if (!str) return "";
  return str
    .toLowerCase()
    .replace(/[“”—’']/g, '"')
    .replace(/[^a-z0-9 ]/g, " ")
    .replace(/\s+/g, " ")
    .trim();
}

// Pre-compute normalized lookup map
const NORMALIZED_LOOKUP = new Map();
for (const [key, val] of Object.entries(ENGLISH_SAMPLE_ANSWERS)) {
  NORMALIZED_LOOKUP.set(normalizeKey(key), val);
}

/**
 * Retrieve the full sample answer for a given speaking prompt, day number, and topic
 * @param {Object} params
 * @param {string} params.prompt - Speaking prompt
 * @param {number} params.day - Day number (1 to 90)
 * @param {string} [params.topic] - Subject topic name
 * @returns {Object} Structured sample answer with metadata, text, paragraphs, and word count
 */
export function getEnglishSampleAnswer({ prompt = "", day = 1, topic = "" }) {
  const normPrompt = normalizeKey(prompt);

  // 1. Exact normalized prompt lookup
  if (NORMALIZED_LOOKUP.has(normPrompt)) {
    const item = NORMALIZED_LOOKUP.get(normPrompt);
    return enrichAnswer(item, prompt, topic, day);
  }

  // 2. Partial search matching across keys
  for (const [key, val] of NORMALIZED_LOOKUP.entries()) {
    if (normPrompt.includes(key) || key.includes(normPrompt)) {
      return enrichAnswer(val, prompt, topic, day);
    }
  }

  // 3. Match by topic keyword
  const normTopic = normalizeKey(topic);
  for (const val of Object.values(ENGLISH_SAMPLE_ANSWERS)) {
    const valTopicNorm = normalizeKey(val.topic);
    if (valTopicNorm && normTopic.includes(valTopicNorm)) {
      return enrichAnswer(val, prompt, topic, day);
    }
  }

  // 4. Fallback: Generate structured dynamic response addressing the prompt directly
  return createDynamicFallbackAnswer({ prompt, day, topic });
}

/**
 * Enriches the answer with computed fields: full text, word count, speaking duration
 */
function enrichAnswer(base, originalPrompt, topic, day) {
  const fullText = base.paragraphs.join("\n\n");
  const wordCount = fullText.split(/\s+/).filter(Boolean).length;
  // Average speaking pace ~ 130 words/min
  const estimatedMins = Math.max(1, Math.round((wordCount / 130) * 10) / 10);

  return {
    ...base,
    prompt: originalPrompt || base.prompt,
    topic: topic || base.topic,
    day,
    text: fullText,
    wordCount,
    estimatedMinutes: estimatedMins,
  };
}

